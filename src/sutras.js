// 把短句併起來：一段 5～12 個字左右，每天抄一段
function makeSegs(lines) {
  const segs = [];
  for (const l of lines) {
    const cur = segs[segs.length - 1];
    const n = cur ? cur.join('').length : 99;
    if (cur && n < 5 && n + l.length <= 12) cur.push(l); else segs.push([l]);
  }
  return segs;
}
