// 出 n 題：先用沒看過的題庫題，混一題程式出的題；seen 是看過的題目（存在玩家資料裡）
export function pickRiddles(n, seen = []) {
  const set = new Set(seen);
  let fresh = BANK.filter((r) => !set.has(r.q));
  if (fresh.length < n) { seen.length = 0; fresh = BANK.slice(); } // 全部看過一輪，重新開始
  const out = [];
  while (out.length < n - 1 && fresh.length) out.push(fresh.splice(Math.floor(Math.random() * fresh.length), 1)[0]);
  const gens = [partRiddle, numRiddle, animalRiddle];
  let g = null; for (let k = 0; k < 6 && !g; k++) g = gens[Math.floor(Math.random() * gens.length)]();
  out.splice(Math.floor(Math.random() * (out.length + 1)), 0, g || fresh[0]);
  out.forEach((r) => { if (BANK.includes(r)) seen.push(r.q); });
  return out;
}
